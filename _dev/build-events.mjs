#!/usr/bin/env node
// Builds /events/ from the markdown files in _events/.
//
//   node _dev/build-events.mjs                 build everything (share images only when missing or stale)
//   node _dev/build-events.mjs --og            also re-render every share image
//   node _dev/build-events.mjs --no-og         skip share images (no Chrome needed)
//   node _dev/build-events.mjs --freeze SLUG   save the event's final potluck list into _events/SLUG.potluck.json
//
// Output (commit it): events/index.html, events/<slug>/index.html, events/<slug>/event.ics,
// events/<slug>/og.jpg, events/events.json (read by the potluck Worker).

import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync, statSync, rmSync, mkdtempSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { CATEGORIES, escapeHtml as h, renderMarkdown, buildIcs, readEvent, isPast } from './events-lib.mjs';
import { initials } from '../_worker/src/initials.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, '_events');
const OUT = join(ROOT, 'events');
const IMG = join(ROOT, 'assets', 'img');
const MARK = '<!-- generated by _dev/build-events.mjs from _events/ — edit the .md file, not this one -->';
const CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';

const config = JSON.parse(readFileSync(join(SRC, 'config.json'), 'utf8'));
const SITE = config.site.replace(/\/$/, '');
const args = process.argv.slice(2);

if (args[0] === '--freeze') {
  await freeze(args[1]);
} else {
  build({ og: args.includes('--og') ? 'all' : args.includes('--no-og') ? 'none' : 'stale' });
}

// ---------------------------------------------------------------------------------------------

function loadEvents() {
  const files = readdirSync(SRC).filter((f) => f.endsWith('.md') && !f.startsWith('_') && f.toLowerCase() !== 'readme.md');
  return files.map((f) => {
    const slug = f.replace(/\.md$/, '');
    const path = join(SRC, f);
    const event = readEvent(readFileSync(path, 'utf8'), slug);
    event.srcPath = path;
    const frozenPath = join(SRC, `${slug}.potluck.json`);
    event.frozen = existsSync(frozenPath) ? JSON.parse(readFileSync(frozenPath, 'utf8')).signups : null;
    if (event.cover) event.coverImg = image(event.cover, `${slug}: cover`);
    event.photoImgs = event.photos.map((p) => ({ ...image(p.name, `${slug}: photo`), alt: p.alt }));
    return event;
  }).sort((a, b) => a.start - b.start);
}

// Find name-480/960/1600.jpg in assets/img.
function image(name, where) {
  const sizes = [480, 960, 1600].filter((w) => existsSync(join(IMG, `${name}-${w}.jpg`)));
  if (!sizes.length) throw new Error(`${where} "${name}" not found: add assets/img/${name}-960.jpg (and -1600.jpg)`);
  const url = (w) => `/assets/img/${name}-${w}.jpg`;
  const mid = sizes.includes(960) ? 960 : sizes[0];
  return {
    src: url(mid),
    large: url(sizes[sizes.length - 1]),
    srcset: sizes.map((w) => `${url(w)} ${w}w`).join(', '),
    file: join(IMG, `${name}-${sizes[sizes.length - 1]}.jpg`),
  };
}

function build({ og }) {
  const events = loadEvents();
  mkdirSync(OUT, { recursive: true });
  const now = new Date();

  for (const e of events) {
    const dir = join(OUT, e.slug);
    mkdirSync(dir, { recursive: true });
    const ogPath = join(dir, 'og.jpg');
    if (og !== 'none') renderShareImage(e, ogPath, og === 'all');
    e.ogImage = existsSync(ogPath) ? `${SITE}/events/${e.slug}/og.jpg`
      : e.coverImg ? `${SITE}${e.coverImg.large}` : `${SITE}/assets/img/heart-night-1600.jpg`;
    writeFileSync(join(dir, 'index.html'), eventPage(e, now));
    writeFileSync(join(dir, 'event.ics'), buildIcs({
      slug: e.slug, title: e.title, start: e.start, end: e.end, where: e.where,
      description: [e.blurb, e.partiful && `RSVP: ${e.partiful}`, `${SITE}/events/${e.slug}/`].filter(Boolean).join('\n\n'),
      url: `${SITE}/events/${e.slug}/`,
    }));
  }

  writeFileSync(join(OUT, 'index.html'), indexPage(events.filter((e) => !e.draft), now));
  writeFileSync(join(OUT, 'events.json'), JSON.stringify({
    events: events.map((e) => ({
      slug: e.slug,
      title: e.title,
      start: e.start.toISOString(),
      end: e.end.toISOString(),
      potluck: e.frozen && e.potluck !== 'off' ? 'closed' : e.potluck,
      closesAt: e.closesAt.toISOString(),
      password: e.password,
      passwordVersion: e.passwordVersion,
    })),
  }, null, 2) + '\n');

  // Remove pages for events whose .md file was deleted (only folders this script made).
  const slugs = new Set(events.map((e) => e.slug));
  for (const d of readdirSync(OUT, { withFileTypes: true })) {
    if (!d.isDirectory() || slugs.has(d.name)) continue;
    const page = join(OUT, d.name, 'index.html');
    if (existsSync(page) && readFileSync(page, 'utf8').includes(MARK)) {
      rmSync(join(OUT, d.name), { recursive: true });
      console.log(`removed events/${d.name}/ (no _events/${d.name}.md)`);
    }
  }
  console.log(`built ${events.length} event${events.length === 1 ? '' : 's'} → events/`);
}

async function freeze(slug) {
  if (!slug) throw new Error('usage: node _dev/build-events.mjs --freeze <slug>');
  if (!existsSync(join(SRC, `${slug}.md`))) throw new Error(`no _events/${slug}.md`);
  const api = process.env.POTLUCK_API || config.api;
  const res = await fetch(`${api}/api/events/${slug}`);
  if (!res.ok) throw new Error(`${api} answered ${res.status}`);
  const { signups } = await res.json();
  // The archive only ever keeps initials, whatever the event's password setting.
  const keep = signups.map(({ id, name, dish, category }) => ({ id, name: initials(name), dish, category }));
  writeFileSync(join(SRC, `${slug}.potluck.json`), JSON.stringify({ frozenAt: new Date().toISOString(), signups: keep }, null, 2) + '\n');
  console.log(`saved ${keep.length} potluck entries → _events/${slug}.potluck.json`);
  build({ og: 'stale' });
}

