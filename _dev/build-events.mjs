// ---- share image ---------------------------------------------------------------------------------

function renderShareImage(e, outPath, force) {
  const inputs = [e.srcPath, fileURLToPath(import.meta.url), e.coverImg?.file].filter(Boolean);
  if (!force && existsSync(outPath)) {
    const outTime = statSync(outPath).mtimeMs;
    if (inputs.every((p) => statSync(p).mtimeMs <= outTime)) return;
  }
  if (!existsSync(CHROME)) {
    console.warn(`(no Chrome at ${CHROME}; ${e.slug} will use its cover photo as the share image)`);
    return;
  }
  const tmp = mkdtempSync(join(tmpdir(), 'og-'));
  const html = join(tmp, 'card.html');
  writeFileSync(html, shareCard(e));
  const png = join(tmp, 'card.png');
  execFileSync(CHROME, [
    '--headless=new', '--disable-gpu', '--hide-scrollbars', '--force-device-scale-factor=1',
    '--window-size=1200,630', '--virtual-time-budget=6000', `--screenshot=${png}`, pathToFileURL(html).href,
  ], { stdio: 'ignore' });
  execFileSync('sips', ['-s', 'format', 'jpeg', '-s', 'formatOptions', '86', png, '--out', outPath], { stdio: 'ignore' });
  rmSync(tmp, { recursive: true });
  console.log(`share image → events/${e.slug}/og.jpg`);
}

